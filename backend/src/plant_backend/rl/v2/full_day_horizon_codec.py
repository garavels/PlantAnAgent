def _mapping(name: str, raw: object) -> dict[str, Any]:
    if not isinstance(raw, Mapping) or any(
        not isinstance(key, str) for key in raw.keys()
    ):
        raise TypeError(f"{name} must be a string-keyed mapping")
    return dict(raw)


def _list(name: str, raw: object) -> list[Any]:
    if not isinstance(raw, list):
        raise TypeError(f"{name} must be a JSON array")
    return raw


def _required(payload: Mapping[str, Any], key: str, *, owner: str) -> Any:
    if key not in payload:
        raise ValueError(f"{owner} is missing {key!r}")
    return payload[key]


def _text(name: str, raw: object, *, allow_empty: bool = False) -> str:
    if not isinstance(raw, str):
        raise TypeError(f"{name} must be a string")
    if not allow_empty and not raw:
        raise ValueError(f"{name} must be non-empty")
    return raw


def _optional_text(name: str, raw: object) -> str | None:
    if raw is None:
        return None
    return _text(name, raw)


def _bool(name: str, raw: object) -> bool:
    if not isinstance(raw, bool):
        raise TypeError(f"{name} must be a bool")
    return raw


def _integer(name: str, raw: object, *, minimum: int | None = None) -> int:
    if isinstance(raw, bool) or not isinstance(raw, Integral):
        raise TypeError(f"{name} must be an integer")
    value = int(raw)
    if minimum is not None and value < minimum:
        raise ValueError(f"{name} must be >= {minimum}")
    return value


def _optional_integer(name: str, raw: object) -> int | None:
    if raw is None:
        return None
    return _integer(name, raw)


def _number(name: str, raw: object, *, minimum: float | None = None) -> float:
    if isinstance(raw, bool) or not isinstance(raw, Real):
        raise TypeError(f"{name} must be a real number")
    value = float(raw)
    if not math.isfinite(value):
        raise ValueError(f"{name} must be finite")
    if minimum is not None and value < minimum:
        raise ValueError(f"{name} must be >= {minimum:g}")
    return value


def _optional_number(name: str, raw: object) -> float | None:
    if raw is None:
        return None
    return _number(name, raw)


def _require_exact(
    name: str,
    raw: Mapping[str, Any],
    rebuilt: Mapping[str, Any],
) -> None:
    if dict(raw) != dict(rebuilt):
        raise ValueError(f"{name} does not exactly rebuild from typed evidence")


def _decode_action(raw: object, *, name: str) -> Action:
    payload = _mapping(name, raw)
    action = Action(
        battery_share=_number(
            f"{name}.battery_share",
            _required(payload, "battery_share", owner=name),
        ),
        electrolyser_share=_number(
            f"{name}.electrolyser_share",
            _required(payload, "electrolyser_share", owner=name),
        ),
        dac_share=_number(
            f"{name}.dac_share", _required(payload, "dac_share", owner=name)
        ),
        methanator_share=_number(
            f"{name}.methanator_share",
            _required(payload, "methanator_share", owner=name),
        ),
        battery_support_kw=_number(
            f"{name}.battery_support_kw",
            _required(payload, "battery_support_kw", owner=name),
        ),
    )
    if Action.sanitised(action) != action:
        raise ValueError(f"{name} is not a sanitizer fixed point")
    _require_exact(name, payload, action.to_dict())
    return action


