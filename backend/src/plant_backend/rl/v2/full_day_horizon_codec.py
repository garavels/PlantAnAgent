def _decode_plan_step(raw: object) -> MPCPlanStepV1:
    name = "MPC plan step"
    payload = _mapping(name, raw)
    bool_fields = {"cold_start", "warmup", "running", "battery_charging"}
    values: dict[str, Any] = {}
    for field in fields(MPCPlanStepV1):
        raw_value = _required(payload, field.name, owner=name)
        if field.name == "index":
            values[field.name] = _integer(f"{name}.{field.name}", raw_value)
        elif field.name in bool_fields:
            values[field.name] = _bool(f"{name}.{field.name}", raw_value)
        else:
            values[field.name] = _number(f"{name}.{field.name}", raw_value)
    step = MPCPlanStepV1(**values)
    _require_exact(name, payload, step.to_dict())
    return step


