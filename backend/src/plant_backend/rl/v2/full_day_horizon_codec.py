"""Detached, fail-closed decoding for absolute-setpoint MPC run evidence.

The run-evidence digest verifier proves that a payload has not changed since its
outer digest was computed.  It does not prove that a freshly re-hashed payload is
the output of the typed evidence model.  This module supplies that stronger
admission boundary: every serialized leaf with a public typed representation is
rebuilt, every ``to_dict()`` result must equal its source mapping, and the complete
run is regenerated by :func:`build_mpc_setpoint_run_evidence`.

No simulator, controller, solver, or private episode state is consulted while
decoding.  Consequently the verifier is suitable for detached M24 artifacts.
"""

