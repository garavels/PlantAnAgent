def _decode_residual(raw: object) -> MPCFirstIntervalResidualV1:
    name = "MPC first-interval residual"
    payload = _mapping(name, raw)
    values: dict[str, Any] = {}
    for field in fields(MPCFirstIntervalResidualV1):
        raw_value = _required(payload, field.name, owner=name)
        if field.name == "decision_index":
            values[field.name] = _integer(f"{name}.{field.name}", raw_value)
        elif field.name == "next_observation_sha256":
            values[field.name] = _text(f"{name}.{field.name}", raw_value)
        else:
            values[field.name] = _number(f"{name}.{field.name}", raw_value)
    residual = MPCFirstIntervalResidualV1(**values)
    _require_exact(name, payload, residual.to_dict())
    return residual


