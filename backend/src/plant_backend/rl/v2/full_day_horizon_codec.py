def decode_mpc_setpoint_event(raw: object) -> MPCSetpointDecisionEventV1:
    """Decode and exactly reproduce one detached success or failure event."""

    payload = _mapping("MPC setpoint event", raw)
    schema = _text(
        "MPC setpoint event schema",
        _required(payload, "schema", owner="MPC setpoint event"),
    )
    if schema == SERVICE_MPC_SETPOINT_DECISION_EVIDENCE_SCHEMA:
        return _decode_success(payload)
    if schema == SERVICE_MPC_SETPOINT_FAILURE_SCHEMA:
        return _decode_failure(payload)
    raise ValueError("MPC setpoint event schema is unsupported")


def decode_mpc_setpoint_run(
    raw: object,
    *,
    settings: ServiceMPCSetpointSettingsV1,
) -> tuple[
    tuple[MPCSetpointDecisionEventV1, ...],
    tuple[tuple[int, ...], ...],
]:
    """Decode the complete typed event graph and dispatcher latency groups."""

    if not isinstance(settings, ServiceMPCSetpointSettingsV1):
        raise TypeError("settings must be ServiceMPCSetpointSettingsV1")
    payload = _mapping("MPC setpoint run evidence", raw)
    if (
        _text(
            "MPC setpoint run format",
            _required(payload, "format", owner="MPC setpoint run evidence"),
        )
        != SERVICE_MPC_SETPOINT_RUN_EVIDENCE_FORMAT
    ):
        raise ValueError("MPC setpoint run evidence format is unsupported")
    if (
        _text(
            "MPC setpoint run settings_sha256",
            _required(payload, "settings_sha256", owner="MPC setpoint run evidence"),
        )
        != settings.sha256
    ):
        raise ValueError("MPC setpoint run settings identity is inconsistent")

    events_raw = _list(
        "MPC setpoint run events",
        _required(payload, "events", owner="MPC setpoint run evidence"),
    )
    dispatcher_raw = _list(
        "MPC setpoint dispatcher latencies",
        _required(payload, "dispatcher_elapsed_ns", owner="MPC setpoint run evidence"),
    )
    events = tuple(decode_mpc_setpoint_event(item) for item in events_raw)
    dispatcher_elapsed_ns = tuple(
        tuple(
            _integer(
                f"MPC dispatcher latency [{group_index}][{latency_index}]",
                latency,
                minimum=0,
            )
            for latency_index, latency in enumerate(
                _list(f"MPC dispatcher latency group {group_index}", group)
            )
        )
        for group_index, group in enumerate(dispatcher_raw)
    )
    return events, dispatcher_elapsed_ns


def verify_mpc_setpoint_run_semantics(
    raw: object,
    *,
    settings: ServiceMPCSetpointSettingsV1,
) -> dict[str, Any]:
    """Rebuild a detached run and return the exact admitted evidence mapping.

    Equality covers every nested record, deterministic digest, identity list,
    aggregate, and latency summary.  A payload whose outer digests were coherently
    recomputed after mutation therefore still fails unless it is exactly a valid
    output of the typed run builder.
    """

    payload = _mapping("MPC setpoint run evidence", raw)
    events, dispatcher_elapsed_ns = decode_mpc_setpoint_run(
        payload,
        settings=settings,
    )
    status = _text(
        "MPC setpoint run status",
        _required(payload, "status", owner="MPC setpoint run evidence"),
    )
    if status not in {"complete", "failed"}:
        raise ValueError("MPC setpoint run status is unsupported")
    rebuilt = build_mpc_setpoint_run_evidence(
        events,
        dispatcher_elapsed_ns,
        settings=settings,
        completed_decisions=_integer(
            "MPC setpoint run completed_decisions",
            _required(
                payload, "completed_decisions", owner="MPC setpoint run evidence"
            ),
            minimum=0,
        ),
        run_succeeded=status == "complete",
        pending_transition=_bool(
            "MPC setpoint run pending_transition",
            _required(payload, "pending_transition", owner="MPC setpoint run evidence"),
        ),
        runner_failure_phase=_optional_text(
            "MPC setpoint run runner_failure_phase",
            _required(
                payload, "runner_failure_phase", owner="MPC setpoint run evidence"
            ),
        ),
        final_observation_sha256=_text(
            "MPC setpoint run final_observation_sha256",
            _required(
                payload,
                "final_observation_sha256",
                owner="MPC setpoint run evidence",
            ),
        ),
    )
    _require_exact("MPC setpoint run evidence", payload, rebuilt)
    return rebuilt


