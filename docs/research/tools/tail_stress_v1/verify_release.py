"""Finalize postflight evidence or authenticate an extracted commission package.

No simulations or new scientific outcomes are generated by this helper.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path

from docs.research.tools.tail_stress_v1 import verify
from docs.research.tools.wholeplant_ppo_v1.portable import digest, file_pin, file_sha


def verify_commission_manifest(root):
    root = Path(root).resolve()
    if root != verify.ROOT:
        raise ValueError("Invoke the extracted module in a fresh interpreter; --root must match its imported source root")
    path = root / "commission-manifest.json"
    manifest = json.loads(path.read_text())
    if manifest.get("schema") != "plantanagent-final-commission-package-v1":
        raise ValueError("Unknown commission package schema")
    verify.same(manifest["sha256"], digest({k:v for k,v in manifest.items() if k != "sha256"}), "commission manifest digest")
    members, original_paths = set(), {}
    for entry in manifest["files"]:
        relative = Path(entry["path"])
        if relative.is_absolute() or ".." in relative.parts or relative.as_posix() in members:
            raise ValueError("Invalid or duplicate member path")
        target = root / relative
        if target.is_symlink() or not target.resolve().is_relative_to(root):
            raise ValueError("Member escapes commission root")
        if target.stat().st_size != entry["bytes"] or file_sha(target) != entry["sha256"]:
            raise ValueError("Commission member differs: " + entry["path"])
        members.add(relative.as_posix())
        if entry.get("original_path"):
            if entry["original_path"] in original_paths:
                raise ValueError("Duplicate original provenance path")
            original_paths[entry["original_path"]] = entry
    for pin in manifest["scientific_bindings"]:
        member = original_paths.get(pin["path"])
        if member is None or any(member[k] != pin[k] for k in ("bytes", "sha256")):
            raise ValueError("A scientific pin lacks its authenticated package member")
    return {"schema": "commission-package-verification-v1", "status": "passed",
            "manifest_sha256": manifest["sha256"], "all_member_hashes_verified": True,
            "all_scientific_bindings_verified": True, "members_checked": len(members),
            "scientific_bindings_checked": len(manifest["scientific_bindings"])}


def finalize(results, output):
    results, output = Path(results).resolve(), Path(output).resolve()
    evidence = verify.Evidence(results)
    replay_path = output / "replay-summary.json"
    replays = json.loads(replay_path.read_text())
    verify.same(replays["freeze_sha256"], evidence.spec["sha256"], "replay freeze")
    if not replays["verified"] or replays["case_count"] != 30 or len(replays["receipts"]) != 30:
        raise ValueError("The exact replay panel is incomplete")
    identities = set()
    for pin in replays["receipts"]:
        receipt = json.loads(evidence.resolve(pin).read_text())
        if not (receipt["verified"] and receipt["all149inputs_and7actions_exact"]
                and receipt["all_interval_rewards_exact"] and receipt["every_physical_state_exact"]
                and receipt["final_ledgers_and_audits_exact"] and receipt["event_states_exact"]):
            raise ValueError("A replay failed")
        if receipt["controller"].startswith("ppo-") and not receipt["normalizer_and_actor_witness_exact"]:
            raise ValueError("A PPO replay lacks exact normalization and actor evidence")
        if receipt["decisions"] != 672 or receipt["physical_states"] != 10081:
            raise ValueError("Replay geometry differs")
        evidence.resolve(receipt["recording"])
        evidence.resolve(receipt["verifier"])
        identities.add((receipt["seed"], receipt["condition"], receipt["controller"]))
    expected = {(verify.SEEDS[0], condition, controller)
                for condition in verify.CONDITIONS for controller in verify.CONTROLLERS}
    verify.same(sorted(identities), sorted(expected), "prescribed replay identities")
    integrity = verify.verify_all(evidence, output / "integrity")
    report = {**integrity, "status": "passed",
        "all_sources_unchanged": True, "all480_case_artifacts_verified": True,
        "exact_replays_passed": True, "prefixes_match_paired_control": True,
        "replay_count": 30, "replay_summary": file_pin(replay_path),
        "integrity_review": file_pin(output / "integrity/review.json"),
        "release_verifier": file_pin(__file__), "completed_at": datetime.now(timezone.utc).isoformat()}
    verify.publish(output / "review.json", report)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("finalize", "manifest"))
    parser.add_argument("--root", type=Path, default=verify.ROOT)
    parser.add_argument("--results", type=Path, default=verify.DEFAULT_RESULTS)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.root.resolve() != verify.ROOT:
        raise ValueError("--root requires a fresh interpreter importing this root's source")
    result = (verify_commission_manifest(args.root) if args.command == "manifest"
              else finalize(args.results, args.output or args.results / "postflight"))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
